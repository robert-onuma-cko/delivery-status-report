"""Load KEY=VALUE pairs from a .env file into os.environ for local runs.

Variables that are already set in the environment always win, so the cloud
routine (which gets its secrets from the environment settings) is unaffected.
"""
import os
from pathlib import Path


def load_dotenv(path):
    path = Path(path)
    if not path.exists():
        return 0
    loaded = 0
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        if key.startswith("export "):
            key = key[len("export "):].strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        if key and key not in os.environ:
            os.environ[key] = value
            loaded += 1
    return loaded
